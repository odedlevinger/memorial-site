import { IsEmail, IsNotEmpty, IsOptional, IsString, IsBoolean, IsIn, MinLength, MaxLength } from 'class-validator';
import { Transform } from 'class-transformer';
import { ApiProperty, ApiPropertyOptional } from '@nestjs/swagger';

/* istanbul ignore next */
const trimStr = ({ value }: { value: unknown }): unknown =>
  typeof value === 'string' ? value.trim() : value;

export class LoginDto {
  @ApiProperty({ example: 'user@example.com' })
  @IsEmail()
  email!: string;

  @ApiProperty({ example: 'supersecret123' })
  @IsNotEmpty()
  @IsString()
  password!: string;
}

export class RegisterDto {
  @ApiProperty({ example: 'user@example.com' })
  @IsEmail()
  email!: string;

  @ApiProperty({ example: 'supersecret123', minLength: 8 })
  @IsNotEmpty()
  @MinLength(8)
  password!: string;

  @ApiProperty({ example: 'Jane', description: 'First name' })
  @IsNotEmpty()
  @IsString()
  @MaxLength(100)
  @Transform(trimStr)
  firstName!: string;

  @ApiPropertyOptional({ example: 'Marie', description: 'Second / middle name (optional)' })
  @IsOptional()
  @IsString()
  @MaxLength(100)
  @Transform(trimStr)
  secondName?: string;

  @ApiProperty({ example: 'Doe', description: 'Last name' })
  @IsNotEmpty()
  @IsString()
  @MaxLength(100)
  @Transform(trimStr)
  lastName!: string;

  @ApiProperty({ example: true, description: 'User must explicitly accept terms' })
  @IsBoolean()
  consent!: boolean;
}

export class RefreshDto {
  @ApiPropertyOptional({ description: 'Mobile clients send refresh token in body; web clients use httpOnly cookie' })
  @IsOptional()
  @IsString()
  refreshToken?: string;
}

export class GoogleCallbackDto {
  @ApiProperty({ description: 'Google authorization code from OAuth redirect' })
  @IsNotEmpty()
  @IsString()
  code!: string;

  @ApiProperty({ description: 'PKCE code verifier generated by the client' })
  @IsNotEmpty()
  @IsString()
  codeVerifier!: string;
}

/**
 * Body for `POST /auth/google/id-token` — Google Identity Services
 * one-tap / button flow (used by the Back Office). The browser obtains
 * the ID token via `google.accounts.id.initialize()` and posts it here
 * directly; the server verifies the JWT against Google's JWKS and
 * either finds the existing Google-linked user or creates one.
 */
export class GoogleIdTokenDto {
  @ApiProperty({ description: 'Google ID token (JWT) from GIS' })
  @IsNotEmpty()
  @IsString()
  idToken!: string;
}

export const SUPPORTED_LANGUAGES = ['en', 'he', 'ro', 'fr', 'es', 'ar'] as const;

export class UpdateLanguageDto {
  @ApiProperty({ example: 'he', description: 'ISO 639-1 language code', enum: SUPPORTED_LANGUAGES })
  @IsNotEmpty()
  @IsString()
  @IsIn([...SUPPORTED_LANGUAGES])
  preferredLanguage!: string;
}

export class DeleteAccountDto {
  @ApiProperty({ example: 'supersecret123', description: 'Current password for re-authentication (FR-016)' })
  @IsNotEmpty()
  @IsString()
  password!: string;

  @ApiProperty({ example: 'delete my account', description: 'Exact confirmation phrase to prevent accidental deletion' })
  @IsNotEmpty()
  @IsString()
  confirmPhrase!: string;
}
